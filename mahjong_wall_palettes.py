CURATED_IDS = tuple(p[0] for p in CURATED)
DERIVED_IDS = tuple(p[0] for p in DERIVED)
ALL_IDS = CURATED_IDS + DERIVED_IDS

DEFAULT_PALETTE = "classic"

_BY_ID = {}
for _p in CURATED:
    _BY_ID[_p[0]] = {"id": _p[0], "name": _p[1], "note": _p[2],
                     "steps": tuple(_p[3]), "group": "", "kind": "curated"}
for _p in DERIVED:
    _BY_ID[_p[0]] = {"id": _p[0], "name": _p[1], "note": "按色名派生，非权威色卡值",
                     "steps": tuple(_p[3]), "group": _p[2], "kind": "derived"}


def all_palettes():
    """返回全部内置方案（精选在前）。"""
    return [_BY_ID[i] for i in ALL_IDS]


def get_palette(pid, fallback=DEFAULT_PALETTE):
    """按 id 取方案；找不到回退默认，绝不抛异常（设置文件可能被手改坏）。"""
    p = _BY_ID.get(str(pid or "").strip())
    if p is None:
        p = _BY_ID[fallback]
    return p


def steps_of(pid, fallback=DEFAULT_PALETTE):
    """取 5 档色阶（tuple[str]）。"""
    return get_palette(pid, fallback)["steps"]


def palette_name(pid):
    return get_palette(pid)["name"]


def groups():
    """派生方案按分组聚合：[(分组名, [(id, 显示名), ...]), ...]，顺序即清单顺序。"""
    out = []
    idx = {}
    for _p in DERIVED:
        g = _p[2]
        if g not in idx:
            idx[g] = len(out)
            out.append((g, []))
        out[idx[g]][1].append((_p[0], _p[1]))
    return out


def _lin(c):
    c = c / 255.0
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def contrast_black(hexs):
    """纯黑底下的 WCAG 对比度，用于自检（生成器与回归都用它）。"""
    h = str(hexs).lstrip("#")
    r, g, b = int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)
    lum = 0.2126 * _lin(r) + 0.7152 * _lin(g) + 0.0722 * _lin(b)
    return (lum + 0.05) / 0.05


def min_contrast(pid):
    """该方案 5 档里最低的对比度。"""
    return min(contrast_black(h) for h in steps_of(pid))
